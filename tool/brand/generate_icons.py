#!/usr/bin/env python3
"""Generates the Settle Up app icon and launch mark (Point to Point design).

The mark is the tether (docs/design/DESIGN.md, "Components"): a filled ink
point (you), a solid line with one chevron near the receiving end, and an
ink ring (the other party), on cool stone.

Run from the repository root:

    python3 tool/brand/generate_icons.py

Writes:
  android/app/src/main/res/drawable/ic_launcher_foreground.xml  (adaptive fg + monochrome)
  android/app/src/main/res/drawable/ic_launch_mark.xml          (launch window, splash)
  android/app/src/main/res/mipmap-*/ic_launcher.png             (legacy square)
  android/app/src/main/res/mipmap-*/ic_launcher_round.png       (legacy round)
  ios/Runner/Assets.xcassets/AppIcon.appiconset/*.png           (full-bleed, opaque)
  docs/design/brand/icon.svg, docs/design/brand/icon-512.png    (store / source)

Needs Pillow. The geometry below is the single source for every output.
"""
import json
import os
import sys

from PIL import Image, ImageDraw

# Tokens (lib/theme/tokens.dart).
INK = (0x16, 0x19, 0x1D)
STONE = (0xEE, 0xF0, 0xEF)

# Geometry in the 108 x 108 adaptive-icon viewport. The visible area of an
# adaptive icon is the centre 72 x 72 (18..90) and the safe zone is the
# centre circle of diameter 66; the mark stays inside it.
CY = 54.0
DOT_X = 33.0  # filled point (you)
RING_X = 75.0  # ring (the other party)
R = 7.5  # outer radius of both points
RING_STROKE = 3.25
LINE_STROKE = 3.25
LINE_START = DOT_X + R
LINE_END = RING_X - R
CHEVRON_TIP = LINE_START + (LINE_END - LINE_START) * 0.71  # as in TetherGlyph
CHEVRON_H = 5.5
CHEVRON_STROKE = 3.25

# Visible square of the adaptive icon, used to map the mark onto legacy and
# iOS icons.
VISIBLE = (18.0, 90.0)

DENSITIES = {
    'mdpi': 48,
    'hdpi': 72,
    'xhdpi': 96,
    'xxhdpi': 144,
    'xxxhdpi': 192,
}

SS = 8  # supersampling factor for raster output


def _f(v):
    s = f'{v:.3f}'.rstrip('0').rstrip('.')
    return s


def vector_paths(color):
    """Android vector drawable <path> elements for the mark."""
    inner = R - RING_STROKE
    line_top = CY - LINE_STROKE / 2
    line_bottom = CY + LINE_STROKE / 2
    # The line overlaps both points by 1 unit so no seam shows.
    return f'''    <!-- Filled point: you. -->
    <path
        android:fillColor="{color}"
        android:pathData="M{_f(DOT_X - R)},{_f(CY)}a{_f(R)},{_f(R)} 0,1 0,{_f(2 * R)},0a{_f(R)},{_f(R)} 0,1 0,{_f(-2 * R)},0z" />
    <!-- Ring: the other party. -->
    <path
        android:fillColor="{color}"
        android:fillType="evenOdd"
        android:pathData="M{_f(RING_X - R)},{_f(CY)}a{_f(R)},{_f(R)} 0,1 0,{_f(2 * R)},0a{_f(R)},{_f(R)} 0,1 0,{_f(-2 * R)},0zM{_f(RING_X - inner)},{_f(CY)}a{_f(inner)},{_f(inner)} 0,1 0,{_f(2 * inner)},0a{_f(inner)},{_f(inner)} 0,1 0,{_f(-2 * inner)},0z" />
    <!-- The line between them. -->
    <path
        android:fillColor="{color}"
        android:pathData="M{_f(LINE_START - 1)},{_f(line_top)}H{_f(LINE_END + 1)}V{_f(line_bottom)}H{_f(LINE_START - 1)}z" />
    <!-- One chevron near the receiving end. -->
    <path
        android:strokeColor="{color}"
        android:strokeWidth="{_f(CHEVRON_STROKE)}"
        android:strokeLineCap="round"
        android:strokeLineJoin="round"
        android:pathData="M{_f(CHEVRON_TIP - CHEVRON_H)},{_f(CY - CHEVRON_H)}L{_f(CHEVRON_TIP)},{_f(CY)}L{_f(CHEVRON_TIP - CHEVRON_H)},{_f(CY + CHEVRON_H)}" />'''


def vector_drawable(color, comment):
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {comment}
     Generated by tool/brand/generate_icons.py; edit the geometry there. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
{vector_paths(color)}
</vector>
'''


def svg(background=True):
    inner = R - RING_STROKE
    ink = '#%02X%02X%02X' % INK
    stone = '#%02X%02X%02X' % STONE
    bg = f'  <rect width="108" height="108" fill="{stone}"/>\n' if background else ''
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="108" height="108">
  <!-- Settle Up app icon: the tether, ink on stone. Generated by
       tool/brand/generate_icons.py. The visible area of the Android
       adaptive icon is the centre 72 x 72. -->
{bg}  <circle cx="{_f(DOT_X)}" cy="{_f(CY)}" r="{_f(R)}" fill="{ink}"/>
  <circle cx="{_f(RING_X)}" cy="{_f(CY)}" r="{_f(R - RING_STROKE / 2)}" fill="none" stroke="{ink}" stroke-width="{_f(RING_STROKE)}"/>
  <rect x="{_f(LINE_START - 1)}" y="{_f(CY - LINE_STROKE / 2)}" width="{_f(LINE_END - LINE_START + 2)}" height="{_f(LINE_STROKE)}" fill="{ink}"/>
  <path d="M{_f(CHEVRON_TIP - CHEVRON_H)} {_f(CY - CHEVRON_H)} L{_f(CHEVRON_TIP)} {_f(CY)} L{_f(CHEVRON_TIP - CHEVRON_H)} {_f(CY + CHEVRON_H)}" fill="none" stroke="{ink}" stroke-width="{_f(CHEVRON_STROKE)}" stroke-linecap="round" stroke-linejoin="round"/>
</svg>
'''


def draw_mark(draw, scale, ox, oy, color):
    """Draws the mark; viewport point (x, y) maps to (ox + x*scale, oy + y*scale)."""

    def p(x, y):
        return (ox + x * scale, oy + y * scale)

    def circle(cx, cy, r, **kw):
        x0, y0 = p(cx - r, cy - r)
        x1, y1 = p(cx + r, cy + r)
        draw.ellipse([x0, y0, x1, y1], **kw)

    circle(DOT_X, CY, R, fill=color)
    # Ring as an annulus: outer disc minus inner disc is not possible with
    # one fill, so draw the outline with the stroke width.
    circle(RING_X, CY, R, outline=color, width=max(1, round(RING_STROKE * scale)))
    x0, y0 = p(LINE_START - 1, CY - LINE_STROKE / 2)
    x1, y1 = p(LINE_END + 1, CY + LINE_STROKE / 2)
    draw.rectangle([x0, y0, x1, y1], fill=color)
    w = CHEVRON_STROKE * scale
    pts = [
        p(CHEVRON_TIP - CHEVRON_H, CY - CHEVRON_H),
        p(CHEVRON_TIP, CY),
        p(CHEVRON_TIP - CHEVRON_H, CY + CHEVRON_H),
    ]
    draw.line(pts, fill=color, width=round(w), joint='curve')
    for x, y in pts:  # round caps and join
        draw.ellipse([x - w / 2, y - w / 2, x + w / 2, y + w / 2], fill=color)


def raster(size, shape):
    """An icon of [size] px. shape: 'square' (full bleed), 'legacy', 'round'."""
    big = size * SS
    img = Image.new('RGBA', (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    if shape == 'square':
        d.rectangle([0, 0, big, big], fill=STONE + (255,))
        inset = 0.0
        side = big
    else:
        # Legacy launcher icons: 44 of 48 dp with a 2 dp margin, like the
        # Material legacy keylines.
        inset = big * 2 / 48
        side = big - 2 * inset
        if shape == 'round':
            d.ellipse([inset, inset, inset + side, inset + side], fill=STONE + (255,))
        else:
            d.rounded_rectangle(
                [inset, inset, inset + side, inset + side],
                radius=side * 0.22,
                fill=STONE + (255,),
            )
    # Map the visible 72 x 72 of the adaptive viewport onto the shape.
    scale = side / (VISIBLE[1] - VISIBLE[0])
    origin = inset - VISIBLE[0] * scale
    draw_mark(d, scale, origin, origin, INK + (255,))
    img = img.resize((size, size), Image.LANCZOS)
    if shape == 'square':
        img = img.convert('RGB')  # iOS and Play want opaque icons
    return img


def write(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    mode = 'wb' if isinstance(data, bytes) else 'w'
    with open(path, mode) as f:
        f.write(data)
    print(path)


def save(img, path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    img.save(path, optimize=True)
    print(path)


def main():
    if not os.path.isfile('pubspec.yaml'):
        sys.exit('run from the repository root')
    res = 'android/app/src/main/res'
    write(
        f'{res}/drawable/ic_launcher_foreground.xml',
        vector_drawable(
            '#FF16191D',
            'Adaptive launcher icon foreground and monochrome layer: the '
            'tether in ink.',
        ),
    )
    write(
        f'{res}/drawable/ic_launch_mark.xml',
        vector_drawable(
            '@color/launch_mark',
            'The tether on the launch window and the Android 12+ splash '
            'screen; ink by day, light ink at night (values-night).',
        ),
    )
    for name, px in DENSITIES.items():
        save(raster(px, 'legacy'), f'{res}/mipmap-{name}/ic_launcher.png')
        save(raster(px, 'round'), f'{res}/mipmap-{name}/ic_launcher_round.png')

    ios = 'ios/Runner/Assets.xcassets/AppIcon.appiconset'
    with open(f'{ios}/Contents.json') as f:
        contents = json.load(f)
    done = set()
    for image in contents['images']:
        name = image.get('filename')
        if not name or name in done:
            continue
        done.add(name)
        pt = float(image['size'].split('x')[0])
        px = round(pt * int(image['scale'].rstrip('x')))
        save(raster(px, 'square'), f'{ios}/{name}')

    write('docs/design/brand/icon.svg', svg())
    save(raster(512, 'square'), 'docs/design/brand/icon-512.png')


if __name__ == '__main__':
    main()
